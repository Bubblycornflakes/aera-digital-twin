def truth_temperature(n):
    """The synthetic works cools through autumn: about 17.5 degrees falling to 11, with a small daily swing."""
    t = np.arange(n) / 96
    return 17.5 - 6.5 * t / (n / 96) + 0.3 * np.sin(2 * np.pi * t)

def simulate_truth(days=21, mismatch=0.0, temperature=True):
    """The synthetic works' real behaviour: benchmark weather through the plant, scaled to DESIGN_FLOW."""
    parts = [dyn.weather("dry"), dyn.weather("rain")]
    flow = np.r_[parts[0][2], parts[1][2][: (days - 14) * 96]][: days * 96]
    feed = np.vstack([parts[0][1], parts[1][1][: (days - 14) * 96]])[: days * 96]
    ctrl = dyn.Controller()
    sc = dyn.Scenario(alpha_scale=1 - mismatch, mu_a_scale=1 - mismatch)
    temp = truth_temperature(len(flow)) if temperature else None
    y0 = dyn.stabilise_at(ctrl, flow[:672].mean(), feed[:672].mean(axis=0), scenario=sc,
                          temperature=None if temp is None else float(temp[:672].mean()), **dyn.MODES["full"])    # the works starts from ITS OWN steady state
    samples = dyn.run_series(ctrl, flow, feed, y0, scenario=sc, temperature=temp)
    eff = np.array([dyn.effluent(r[2:]) for r in samples])
    kla5 = samples[:, 2 + dyn.I_KA + 1]
    kla = np.stack([np.zeros(len(flow)), np.zeros(len(flow)), np.full(len(flow), 240.0), np.full(len(flow), 240.0), kla5], axis=1)
    ae = (dyn.SOSAT * kla * dyn.VOLUME).sum(axis=1) / (1.8 * 1000)
    f = DESIGN_FLOW / Q_BENCH
    return dict(temp=temp, flow=flow * f, nh4_in=feed[:, 9], cod_in=characterise.total_cod(feed), nh4_out=eff[:, 9],
                do=samples[:, 2 + 52 + 7], kwh_d=ae * f)

def generate(out_dir, days=21, mismatch=0.0, messy=True, seed=0, temperature=True):
    """Write historian.csv and site.toml into out_dir. Returns the folder. With temperature=True the works cools through
    autumn and a Temp_C column and tag are written; with False it stays at 15 degrees and no temperature is recorded."""
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    rng = np.random.default_rng(seed)
    t = simulate_truth(days, mismatch, temperature)
    n = len(t["flow"])
    df = pd.DataFrame(dict(
        Q_in=t["flow"] / 24 * (1 + rng.normal(0, 0.01, n)),
        NH4_in=t["nh4_in"] * (1 + rng.normal(0, 0.03, n)),
        COD_in=t["cod_in"] * (1 + rng.normal(0, 0.03, n)),
        NH4_out=np.maximum(t["nh4_out"] * (1 + rng.normal(0, 0.05, n)) + rng.normal(0, 0.05, n), 0),
        DO_5=np.maximum(t["do"] + rng.normal(0, 0.03, n), 0),
        Blower_kW=t["kwh_d"] / 24 * BLOWER_FACTOR * (1 + rng.normal(0, 0.015, n)),
    ))
    if temperature:
        df["Temp_C"] = t["temp"] + rng.normal(0, 0.05, n)
    utc = START_UTC + pd.to_timedelta(np.arange(n) * 15, unit="min")
    local = utc.tz_convert("Europe/London")
    df.insert(0, "Timestamp", [x.strftime("%d/%m/%Y %H:%M") for x in local])           # local clock text, repeated hour included
    df = df.round(3).astype(object)
    if messy:
        df.loc[5 * 96 + 10: 5 * 96 + 58, "NH4_out"] = np.nan                           # analyser offline for 12 hours
        df.loc[8 * 96: 8 * 96 + 31, "DO_5"] = 1.874                                    # stuck DO probe for 8 hours
        df.loc[3 * 96 + 5, "Q_in"] = -999                                              # logger error value
        df.loc[7 * 96 + 40, "NH4_in"] = "N/A"
        df.loc[10 * 96 + 3, "Blower_kW"] = "Bad"
        df.loc[12 * 96 + 70, "NH4_in"] = 9999                                          # spike beyond any physical value
        df = pd.concat([df, df.iloc[[400, 401]]]).sort_index(kind="stable")            # two duplicated rows
    df.to_csv(out / "historian.csv", index=False)
    (out / "site.toml").write_text(TOML.replace("#[data.tags.temperature]\n#column", "[data.tags.temperature]\ncolumn").replace('#unit = "degC"', 'unit = "degC"') if temperature else TOML)
    return out
