"""The shadow-mode report as one standalone HTML page (no external files), written for an engineer who has not seen AERA."""
import html as _html

e = _html.escape
VERDICT = {
    "validated": ("good", "The model reproduces your recorded data."),
    "partly_validated": ("warn", "The model matches on the one indicator that could be checked."),
    "not_validated": ("bad", "The model does NOT reproduce your recorded data well enough. Treat everything below as research only."),
    "cannot_validate": ("warn", "There was nothing recorded to check the model against. Treat everything below as research only."),
}
STYLE = ("body{font:15px/1.55 system-ui,sans-serif;max-width:980px;margin:2rem auto;padding:0 1rem;color:#1d2b2a}h1{margin-bottom:.2rem}"
         "table{border-collapse:collapse;margin:.6rem 0 1.2rem;width:100%}td,th{border:1px solid #ccd;padding:5px 9px;text-align:left;font-size:14px}"
         "th{background:#eef3f3}.banner{padding:14px 18px;border-radius:8px;margin:1rem 0;font-size:16px}.good{background:#dff3e8;border-left:6px solid #1b9e77}"
         ".warn{background:#fff3d6;border-left:6px solid #d9a21b}.bad{background:#fbe3dc;border-left:6px solid #d95f02}.muted{color:#5b6b6a;font-size:13px}"
         "h2{margin-top:2rem;border-bottom:1px solid #ccd;padding-bottom:.2rem}svg{background:#fafcfc;border:1px solid #dde}")

def chart(series, title, unit, width=860, height=220):
    """Daily lines: model today (grey), model candidate (teal), recorded (dots)."""
    days = series["day"]
    lines = {"Model, today's control": series["baseline"], "Model, candidate": series["candidate"]}
    allv = [v for s in list(lines.values()) + [series.get("observed", [])] for v in s if v is not None]
    if not days or not allv:
        return ""
    lo, hi = min(allv), max(allv)
    span = (hi - lo) or 1.0
    x = lambda i: 56 + i / max(len(days) - 1, 1) * (width - 76)
    y = lambda v: height - 34 - (v - lo) / span * (height - 60)
    parts = []
    for (name, vals), colour in zip(lines.items(), ("#7b8a89", "#1b9e77")):
        parts.append(f'<polyline fill="none" stroke="{colour}" stroke-width="2" points="{" ".join(f"{x(i):.1f},{y(v):.1f}" for i, v in enumerate(vals))}"/>')
    for i, v in enumerate(series.get("observed", [])):
        if v is not None:
            parts.append(f'<circle cx="{x(i):.1f}" cy="{y(v):.1f}" r="3.2" fill="#d95f02"/>')
    legend = '<text x="58" y="14" font-size="11" fill="#7b8a89">grey line: model, today</text><text x="190" y="14" font-size="11" fill="#1b9e77">green line: model, candidate</text>' \
             + ('<text x="350" y="14" font-size="11" fill="#d95f02">orange dots: recorded</text>' if series.get("observed") else "")
    fmt = lambda v: f"{v:,.0f}" if abs(v) >= 100 else f"{v:.2f}"
    axes = (f'<text x="4" y="{y(hi) + 4:.0f}" font-size="10">{fmt(hi)}</text><text x="4" y="{y(lo) + 4:.0f}" font-size="10">{fmt(lo)}</text>'
            f'<text x="56" y="{height - 6}" font-size="10">{e(days[0])}</text><text x="{width - 90}" y="{height - 6}" font-size="10">{e(days[-1])}</text>')
    return f'<h3>{e(title)} <span class="muted">({e(unit)})</span></h3><svg viewBox="0 0 {width} {height}" width="100%" role="img" aria-label="{e(title)}">{legend}{axes}{"".join(parts)}</svg>'

def html(r):
    v = r["validation"]
    cls, line = VERDICT[v["status"]]
    rec = r.get("recommendation")
    ap = r["appraisal"]
    out = [f'<!doctype html><meta charset="utf-8"><title>Shadow mode report: {e(r["site"])}</title><style>{STYLE}</style>',
           f'<h1>Shadow mode report: {e(r["site"])}</h1><p class="muted">Window {e(r["window"]["start"][:10])} to {e(r["window"]["end"][:10])} '
           f'({r["window"]["days"]} days, first {r["window"]["warmup_days_excluded"]:g} excluded as model warm-up). Advice only: this tool does not read from or write to any plant.</p>',
           f'<div class="banner {cls}"><b>Can the model be trusted on your data?</b> {e(line)}</div>']
    if r.get("synthetic"):
        out.insert(2, '<div class="banner warn"><b>SYNTHETIC DATA.</b> This report is a demonstration. The "recorded" data was generated by the model itself, so the fit is artificially good, and nothing here says anything about a real works.</div>')
    if rec:
        rc = {"ready_for_operator_review": "good", "research_only": "warn", "rejected": "bad"}[rec["status"]]
        d = ap["difference"]
        out.append(f'<div class="banner {rc}"><b>Recommendation: {e(rec["status"].replace("_", " "))}.</b> {e(rec["reason"])}<br>'
                   f'DO setpoint {r["current_control"]["do_setpoint"]:g} to {r["candidate"].get("so_ref", r["current_control"]["do_setpoint"]):g} mg/l: '
                   f'aeration energy {d["energy_pct"]:+.1f}% ({d["energy_kwh"]:+,.0f} kWh over the window, about {d["cost_gbp"]:+,.0f} pounds and {d["carbon_t"]:+.2f} t CO2e). '
                   + (f'Staged steps: {", ".join(map(str, rec["staged_setpoints"]))}.' if rec["staged_setpoints"] else "") + '</div>')
    cal = r.get("calibration")
    if cal:
        out.append("<h2>Calibration</h2>")
        if cal.get("used"):
            h = cal["held_out"]
            out.append(f'<p>The plant was fitted to your first {cal["train_days"]} days, then checked on the {cal["test_days"]} days it never saw. Nitrifier activity '
                       f'{cal["params"]["mu_a_scale"]:g} times the benchmark; oxygen transfer {cal["params"]["alpha_scale"]:g} times the benchmark. On the held-out days the effluent '
                       f'ammonium error fell from {h["nh4_error_before"]} to {h["nh4_error_after"]} (standardised), a {h["improvement_pct"]}% improvement. The model check below is judged on those held-out days only.</p>')
        else:
            out.append(f'<p><b>Calibration was not used</b> ({e(cal["status"].replace("_", " "))}); the benchmark plant was kept.</p>')
        out.append("<ul>" + "".join(f"<li>{e(t)}</li>" for t in cal.get("notes", [])) + "</ul>")
    out.append("<h2>1. Does the model match your records?</h2>")
    if v.get("evaluated_on"):
        out.append(f'<p class="muted">Judged on {e(v["evaluated_on"])}.</p>')
    out.append("<p>A model is only useful if it reproduces what actually happened. We replayed your recorded influent through the model with your current control and compared the result with what you recorded.</p>")
    out.append("<table><tr><th>Indicator</th><th>Days compared</th><th>Nash-Sutcliffe</th><th>Bias</th><th>R squared</th><th>Mean absolute error</th></tr>")
    for name, m in v["indicators"].items():
        level = m.get("kind") == "level"
        mark = "not scored" if m.get("ok") is None else ("pass" if m["ok"] else "FAIL")
        out.append(f'<tr><td>{e(name.replace("_", " "))} <b>({mark})</b></td><td>{m["n"]}</td><td>{"not used" if level else m["nse"]}</td><td>{m["bias_pct"]}%</td><td>{m["r2"]}</td>'
                   f'<td>{(str(m["mae"]) + " mg/l") if level else ""}</td></tr>')
    out.append(f'</table><p class="muted">Pass mark: Nash-Sutcliffe at least {v["thresholds"]["nse_min"]:g} and bias within {v["thresholds"]["bias_max_pct"]:g}% (1 is a perfect match, 0 is no better than the average). Dissolved oxygen is held near its setpoint, so it is judged by its average error instead: {v["thresholds"].get("do_mae_max", 0.3):g} mg/l or less. These pass marks were chosen by the author of this tool, not by a standard; set your own in the configuration.</p><ul>')
    out += [f"<li>{e(t)}</li>" for t in v["reasons"]]
    out.append("</ul>")
    s = r["series"]
    out.append(chart(s["effluent_nh4"], "Effluent ammonium, daily", "mg N/l"))
    out.append(chart(s["aeration_kwh_d"], "Aeration energy per day", "kWh/d"))
    out.append("<h2>2. Permit-style limits</h2><p>Modelled effluent against the limits you configured. A short window gives an indication of risk, not a statement of compliance.</p>")
    if r["consents"]:
        out.append("<table><tr><th>Limit</th><th>Today's control</th><th>Candidate</th></tr>")
        for c in r["consents"]:
            out.append(f'<tr><td>{e(c["baseline"]["name"])}</td><td>{e(c["baseline"]["status"])}: {e(c["baseline"]["detail"])}</td><td>{e(c["candidate"]["status"])}: {e(c["candidate"]["detail"])}</td></tr>')
        out.append("</table>")
    else:
        out.append("<p>No consents were configured.</p>")
    out.append(f'<p>Time with dissolved oxygen below 0.5 mg/l (a nitrous oxide risk): today {100 * r["low_do_share"]["baseline"]:.1f}%, candidate {100 * r["low_do_share"]["candidate"]:.1f}%.</p>')
    out.append("<h2>3. Energy, cost and carbon</h2><table><tr><th></th><th>Today's control</th><th>Candidate</th></tr>")
    b, c = ap["baseline"], ap["candidate"]
    for label, k in (("Energy over the window (kWh)", "energy_kwh"), ("Energy per day (kWh)", "energy_kwh_per_day"), ("Cost (pounds)", "cost_gbp"), ("Carbon (t CO2e)", "carbon_t")):
        out.append(f"<tr><td>{label}</td><td>{b[k]:,}</td><td>{c[k]:,}</td></tr>")
    out.append(f'</table><p class="muted">Cost range (tariff uncertainty) {b["cost_gbp_range"][0]:,} to {b["cost_gbp_range"][1]:,} pounds; carbon range {b["carbon_t_range"][0]} to {b["carbon_t_range"][1]} t. '
               f'{"Energy is scaled to your recorded blower energy." if b["calibrated"] else "Energy is NOT calibrated to recorded blower power; the level is the model default."} '
               f'Annualised today: {b["annualised"]["energy_kwh"]:,} kWh, {b["annualised"]["cost_gbp"]:,} pounds, {b["annualised"]["carbon_t"]} t. {e(b["annualised"]["note"])}</p>')
    if r.get("sweep"):
        out.append("<h2>4. What if the DO setpoint were different?</h2><table><tr><th>Setpoint (mg/l)</th><th>Energy (kWh/d)</th><th>Cost over window (pounds)</th><th>Mean effluent ammonium</th><th>Time below 0.5 mg/l</th><th>Limits exceeded</th></tr>")
        for t in r["sweep"]:
            out.append(f'<tr><td>{t["so_ref"]:g}</td><td>{t["energy_kwh_per_day"]:,}</td><td>{t["cost_gbp"]:,}</td><td>{t["mean_effluent_nh4"]}</td><td>{t["low_do_pct"]}%</td><td>{e(", ".join(t["consents_exceeded"]) or "none")}</td></tr>')
        out.append("</table>")
    dq = r["data_quality"]
    out.append(f'<h2>Data used</h2><p>{e(dq["file"])}: {dq["rows_read"]:,} rows over {dq["days"]} days. ' + (f"{len(dq['issues'])} thing(s) to look at: " if dq["issues"] else "No data problems found.") + "</p><ul>")
    out += [f"<li>{e(t)}</li>" for t in dq["issues"] + dq["notes"]]
    out.append("</ul><h2>What this report does not tell you</h2><ul>" + "".join(f"<li>{e(a)}</li>" for a in r["assumptions"]) + "</ul>")
    if rec:
        out.append("<h2>Checks applied to the recommendation</h2><table><tr><th>Check</th><th>Result</th><th>Detail</th></tr>" + "".join(
            f'<tr><td>{e(c["name"])}</td><td>{"pass" if c["ok"] else "FAIL"}</td><td>{e(c["detail"])}</td></tr>' for c in rec["checks"]) + f'</table><p class="muted">{e(rec["statement"])}</p>')
    return "\n".join(out)
