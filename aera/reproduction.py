"""Compare the closed loop BSM1 implementation with the published dry weather reference.

    python -m aera.reproduction > docs/BSM1_REPRODUCTION.md
"""
import numpy as np
from . import bsm1_dynamic as dyn
from .reference_values import PUBLISHED as P, PUBLISHED_WEATHER as PW

def rows(result_indices, steady):
    i = result_indices
    return [
        ("Internal recycle at steady state (m3/d)", steady["qintr"], P["qintr_steady"]),
        ("Aeration energy, updated index (kWh/d)", i["aeration_energy_kwh_d"], P["aeration_energy_kwh_d"]),
        ("Effluent quality index, updated (kg pollution units/d)", i["eqi"], P["eqi"]),
        ("Average effluent ammonium (g N/m3)", i["average"]["snh"], P["snh_avg"]),
        ("Average effluent total nitrogen (g N/m3)", i["average"]["total_n"], P["total_n_avg"]),
        ("Average effluent suspended solids (g/m3)", i["average"]["tss"], P["tss_avg"]),
        ("Average effluent total COD (g/m3)", i["average"]["cod"], P["cod_avg"]),
        ("Average effluent BOD5 (g/m3)", i["average"]["bod5"], P["bod5_avg"]),
        ("Total nitrogen over 18 g/m3 (share of time)", i["share_over_limit"]["total_n"], P["over_total_n"]),
        ("Ammonium over 4 g/m3 (share of time)", i["share_over_limit"]["snh"], P["over_snh"]),
        ("95th percentile ammonium (g N/m3)", i["p95"]["snh"], P["p95_snh"]),
        ("95th percentile total nitrogen (g N/m3)", i["p95"]["total_n"], P["p95_total_n"]),
    ]

def weather_rows(i, ref):
    return [
        ("Aeration energy, updated index (kWh/d)", i["aeration_energy_kwh_d"], ref["aeration_energy_kwh_d"]),
        ("Effluent quality index, updated", i["eqi"], ref["eqi"]),
        ("Average effluent ammonium (g N/m3)", i["average"]["snh"], ref["snh_avg"]),
        ("Average effluent total nitrogen (g N/m3)", i["average"]["total_n"], ref["total_n_avg"]),
        ("Average effluent suspended solids (g/m3)", i["average"]["tss"], ref["tss_avg"]),
        ("Total nitrogen over limit (share of time)", i["share_over_limit"]["total_n"], ref["over_total_n"]),
        ("Ammonium over limit (share of time)", i["share_over_limit"]["snh"], ref["over_snh"]),
        ("Suspended solids over limit (share of time)", i["share_over_limit"]["tss"], ref["over_tss"]),
        ("95th percentile ammonium (g N/m3)", i["p95"]["snh"], ref["p95_snh"]),
        ("95th percentile total nitrogen (g N/m3)", i["p95"]["total_n"], ref["p95_total_n"]),
    ]

def table_md(table):
    out = ["| Quantity | AERA | Published | Difference | Relative |", "| --- | --- | --- | --- | --- |"]
    for name, value, ref in table:
        rel = f"{100 * (value - ref) / ref:+.1f}%" if ref > 1e-9 else "n/a"
        out.append(f"| {name} | {value:.4g} | {ref:.4g} | {value - ref:+.3g} | {rel} |")
    return out

def markdown(table, mode, weathers=None):
    out = ["# BSM1 closed loop reproduction", "",
           "AERA closed loop BSM1 against the published dry weather results (days 7 to 14). Generated by "
           f"`python -m aera.reproduction` with solver mode `{mode}`. Source: BSM1_R2019b, Results/closedloop_dyn.pdf.", "",
           "## Dry weather", ""]
    out += table_md(table)
    for name, wtable in (weathers or {}).items():
        out += ["", f"## {name.capitalize()} weather", ""] + table_md(wtable)
    allrows = list(table) + [r for w in (weathers or {}).values() for r in w]
    worst = max(abs((v - r) / r) for _, v, r in allrows if r > 0.05)
    out += ["", f"Largest relative difference on quantities above 0.05: {100 * worst:.1f}%.", "",
            "Protocol: 100 days closed loop with constant influent and ideal sensors, then one noisy 14 day dry weather run "
            "whose final state starts the evaluated run, as in the published protocol (the published run uses 500 days "
            "for the first step; the steady state is reached well before 100). Sensor noise and delays follow "
            "`sensornoise.mat` and the class A and B0 models. Differences can come from the solver, interpolation of the "
            "noise file, and the fixed 15 degree Celsius kinetics of the verified plant model.", "",
            "Not reproduced here: pumping and mixing energy and sludge production."]
    return "\n".join(out)

if __name__ == "__main__":
    steady = dyn.stabilise(**dyn.MODES["full"])
    result = dyn.run(mode="full")
    weathers = {w: weather_rows(dyn.indices(dyn.run(scenario=dyn.Scenario(weather=w), mode="full")), PW[w]) for w in PW}
    print(markdown(rows(dyn.indices(result), dict(qintr=float(steady[dyn.I_QA]))), "full", weathers))
